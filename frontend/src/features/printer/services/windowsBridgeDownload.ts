/**
 * Generates and downloads a self-contained Windows .bat launcher (using built-in PowerShell + winspool.drv)
 * so any Windows PC accessing the web-hosted POS can print raw ESC/POS receipts and kick RJ11 cash drawers
 * through the standard Windows printer driver — no Node.js, no git repo, and no Zadig required.
 */

export function buildWindowsBridgeBatContent(): string {
  return [
    '@echo off',
    "title Monk's Dream POS - Windows Printer & Cash Drawer Bridge",
    "echo Starting Monk's Dream Windows Printer Bridge on http://127.0.0.1:12111 ...",
    'echo Keep this window open while the POS counter terminal is running.',
    'echo.',
    "powershell -NoProfile -ExecutionPolicy Bypass -Command \"$s = [System.IO.File]::ReadAllText('%~f0'); $m = '# === POWERSHELL_START ==='; $idx = $s.LastIndexOf($m); Invoke-Expression $s.Substring($idx + $m.Length)\"",
    'pause',
    'exit /b',
    '',
    '# === POWERSHELL_START ===',
    '$ErrorActionPreference = "Stop"',
    '',
    '$csharp = @"',
    'using System;',
    'using System.Runtime.InteropServices;',
    '',
    'public class RawPrinterHelper {',
    '  [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Ansi)]',
    '  public class DOCINFOA {',
    '    [MarshalAs(UnmanagedType.LPStr)] public string pDocName;',
    '    [MarshalAs(UnmanagedType.LPStr)] public string pOutputFile;',
    '    [MarshalAs(UnmanagedType.LPStr)] public string pDataType;',
    '  }',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "OpenPrinterA", SetLastError = true, CharSet = CharSet.Ansi, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool OpenPrinter([MarshalAs(UnmanagedType.LPStr)] string szPrinter, out IntPtr hPrinter, IntPtr pd);',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "ClosePrinter", SetLastError = true, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool ClosePrinter(IntPtr hPrinter);',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "StartDocPrinterA", SetLastError = true, CharSet = CharSet.Ansi, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool StartDocPrinter(IntPtr hPrinter, Int32 level, [In, MarshalAs(UnmanagedType.LPStruct)] DOCINFOA di);',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "EndDocPrinter", SetLastError = true, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool EndDocPrinter(IntPtr hPrinter);',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "StartPagePrinter", SetLastError = true, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool StartPagePrinter(IntPtr hPrinter);',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "EndPagePrinter", SetLastError = true, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool EndPagePrinter(IntPtr hPrinter);',
    '',
    '  [DllImport("winspool.Drv", EntryPoint = "WritePrinter", SetLastError = true, ExactSpelling = true, CallingConvention = CallingConvention.StdCall)]',
    '  public static extern bool WritePrinter(IntPtr hPrinter, IntPtr pBytes, Int32 dwCount, out Int32 dwWritten);',
    '',
    '  public static void SendBytes(string szPrinterName, byte[] bytes) {',
    '    IntPtr pUnmanagedBytes = Marshal.AllocCoTaskMem(bytes.Length);',
    '    Marshal.Copy(bytes, 0, pUnmanagedBytes, bytes.Length);',
    '    IntPtr hPrinter = IntPtr.Zero;',
    '    DOCINFOA di = new DOCINFOA();',
    '    di.pDocName = "Monks Dream ESC/POS Job";',
    '    di.pDataType = "RAW";',
    '    try {',
    '      if (!OpenPrinter(szPrinterName.Normalize(), out hPrinter, IntPtr.Zero)) {',
    '        throw new Exception("OpenPrinter failed (" + Marshal.GetLastWin32Error() + ") for " + szPrinterName);',
    '      }',
    '      if (!StartDocPrinter(hPrinter, 1, di)) {',
    '        throw new Exception("StartDocPrinter failed (" + Marshal.GetLastWin32Error() + ")");',
    '      }',
    '      if (!StartPagePrinter(hPrinter)) {',
    '        throw new Exception("StartPagePrinter failed (" + Marshal.GetLastWin32Error() + ")");',
    '      }',
    '      int written = 0;',
    '      if (!WritePrinter(hPrinter, pUnmanagedBytes, bytes.Length, out written)) {',
    '        throw new Exception("WritePrinter failed (" + Marshal.GetLastWin32Error() + ")");',
    '      }',
    '      EndPagePrinter(hPrinter);',
    '      EndDocPrinter(hPrinter);',
    '    } finally {',
    '      if (hPrinter != IntPtr.Zero) ClosePrinter(hPrinter);',
    '      Marshal.FreeCoTaskMem(pUnmanagedBytes);',
    '    }',
    '  }',
    '}',
    '"@',
    'Add-Type -TypeDefinition $csharp',
    '',
    'function Get-TargetPrinter {',
    '  if ($env:PRINTER_NAME) { return $env:PRINTER_NAME }',
    '  $printers = Get-CimInstance -ClassName Win32_Printer | Select-Object Name, Default, PortName',
    "  $thermal = $printers | Where-Object { $_.Name -match 'POS|80|58|57|Thermal|Receipt|Xprinter|Epson|Rongta|Star|Bixolon|Munbyn' -or $_.PortName -match 'USB' } | Select-Object -First 1",
    '  if ($thermal) { return $thermal.Name }',
    '  $def = $printers | Where-Object { $_.Default -eq $true } | Select-Object -First 1',
    '  if ($def) { return $def.Name }',
    '  $first = $printers | Select-Object -First 1',
    '  if ($first) { return $first.Name }',
    '  return $null',
    '}',
    '',
    '$targetPrinter = Get-TargetPrinter',
    'Write-Host "[Bridge] Target Windows Printer: $targetPrinter" -ForegroundColor Green',
    '',
    '$listener = New-Object System.Net.HttpListener',
    '$listener.Prefixes.Add("http://127.0.0.1:12111/")',
    '$listener.Start()',
    'Write-Host "[Bridge] Listening on http://127.0.0.1:12111/ (Ready for web-hosted POS)" -ForegroundColor Cyan',
    '',
    'while ($listener.IsListening) {',
    '  try {',
    '    $ctx = $listener.GetContext()',
    '    $req = $ctx.Request',
    '    $res = $ctx.Response',
    '    $res.Headers.Add("Access-Control-Allow-Origin", "*")',
    '    $res.Headers.Add("Access-Control-Allow-Methods", "GET, POST, OPTIONS")',
    '    $res.Headers.Add("Access-Control-Allow-Headers", "Content-Type, Access-Control-Request-Private-Network")',
    '    $res.Headers.Add("Access-Control-Allow-Private-Network", "true")',
    '',
    '    if ($req.HttpMethod -eq "OPTIONS") {',
    '      $res.StatusCode = 204',
    '      $res.Close()',
    '      continue',
    '    }',
    '',
    '    $path = $req.Url.AbsolutePath',
    '    $jsonOut = "{}"',
    '    $statusCode = 200',
    '',
    '    if ($req.HttpMethod -eq "GET" -and $path -eq "/status") {',
    '      $targetPrinter = Get-TargetPrinter',
    '      $st = if ($targetPrinter) { "CONNECTED" } else { "OFFLINE" }',
    '      $dev = if ($targetPrinter) { $targetPrinter } else { "No Windows Printer Detected" }',
    '      $jsonOut = (@{ status = $st; device = $dev; platform = "win32"; version = "1.2.0" } | ConvertTo-Json -Compress)',
    '    } elseif ($req.HttpMethod -eq "POST" -and $path -eq "/print") {',
    '      $ms = New-Object System.IO.MemoryStream',
    '      $req.InputStream.CopyTo($ms)',
    '      $bytes = $ms.ToArray()',
    '      $ms.Dispose()',
    '      $targetPrinter = Get-TargetPrinter',
    '      if (-not $targetPrinter) { throw "No Windows printer found." }',
    '      [RawPrinterHelper]::SendBytes($targetPrinter, $bytes)',
    '      Write-Host "[Bridge] Sent $($bytes.Length) raw bytes to $targetPrinter"',
    '      $jsonOut = \'{"success":true}\'',
    '    } elseif ($req.HttpMethod -eq "POST" -and $path -eq "/kick") {',
    '      $targetPrinter = Get-TargetPrinter',
    '      if (-not $targetPrinter) { throw "No Windows printer found." }',
    '      [byte[]]$kickBytes = @(0x1B,0x70,0x00,0x3C,0xFF, 0x1B,0x70,0x01,0x3C,0xFF)',
    '      [RawPrinterHelper]::SendBytes($targetPrinter, $kickBytes)',
    '      Write-Host "[Bridge] Cash drawer kick sent (Pin 2 + Pin 5) to $targetPrinter"',
    '      $jsonOut = \'{"success":true,"kicked":true}\'',
    '    } else {',
    '      $statusCode = 404',
    '      $jsonOut = \'{"error":"Not found"}\'',
    '    }',
    '',
    '    $buf = [System.Text.Encoding]::UTF8.GetBytes($jsonOut)',
    '    $res.StatusCode = $statusCode',
    '    $res.ContentType = "application/json"',
    '    $res.ContentLength64 = $buf.Length',
    '    $res.OutputStream.Write($buf, 0, $buf.Length)',
    '    $res.Close()',
    '  } catch {',
    '    try {',
    '      $errJson = (@{ success = $false; error = $_.Exception.Message } | ConvertTo-Json -Compress)',
    '      $ebuf = [System.Text.Encoding]::UTF8.GetBytes($errJson)',
    '      $res.StatusCode = 500',
    '      $res.ContentType = "application/json"',
    '      $res.ContentLength64 = $ebuf.Length',
    '      $res.OutputStream.Write($ebuf, 0, $ebuf.Length)',
    '      $res.Close()',
    '    } catch {}',
    '    Write-Host "[Bridge] Error: $($_.Exception.Message)" -ForegroundColor Red',
    '  }',
    '}',
  ].join('\r\n');
}

export function downloadWindowsPrinterBridgeBat(): boolean {
  if (typeof document === 'undefined' || typeof Blob === 'undefined') {
    return false;
  }
  const content = buildWindowsBridgeBatContent();
  const blob = new Blob([content], { type: 'application/octet-stream' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'monks-dream-printer-bridge.bat';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
  return true;
}
